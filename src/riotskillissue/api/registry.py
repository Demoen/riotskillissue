@dataclass(frozen=True)
class ParameterSpec:
    name: str
    wire_name: str
    location: str
    required: bool
    annotation: str
    description: Optional[str]
    has_default: bool
    default: Any
    constraints: Mapping[str, Any]
    examples: tuple[Any, ...]
    schema: Mapping[str, Any]


@dataclass(frozen=True)
class RequestBodySpec:
    required: bool
    annotation: str
    description: Optional[str]
    media_type: str
    examples: tuple[Any, ...]
    schema: Mapping[str, Any]


@dataclass(frozen=True)
class OperationSpec:
    operation_id: str
    accessor_path: str
    source: str
    game: str
    service: str
    summary: Optional[str]
    method: str
    path: Optional[str]
    route_kind: Optional[str]
    allowed_routes: tuple[str, ...]
    auth_mode: str
    auth_schemes: tuple[str, ...]
    auth_scopes: tuple[str, ...]
    parameters: tuple[ParameterSpec, ...]
    request_body: Optional[RequestBodySpec]
    response_type: str
    response_adapter: Optional[str]
    successful_statuses: tuple[int | str, ...]
    no_content_statuses: tuple[int | str, ...]
    is_write: bool
    mutation_metadata: Mapping[str, Any]
    cache_user_scoped: bool
    mcp_visible: bool
    input_schema: Mapping[str, Any]

    @property
    def is_read(self) -> bool:
        return not self.is_write


class OperationRegistry(Mapping[str, OperationSpec]):
    def __init__(self, operations: tuple[OperationSpec, ...]) -> None:
        by_id = {operation.operation_id: operation for operation in operations}
        if len(by_id) != len(operations):
            raise ValueError("Operation IDs must be unique")
        self._operations = operations
        self._by_id = by_id

    def __getitem__(self, operation_id: str) -> OperationSpec:
        return self._by_id[operation_id]

    def __iter__(self) -> Iterator[str]:
        return iter(self._by_id)

    def __len__(self) -> int:
        return len(self._by_id)

    def find(
        self,
        query: str = "",
        *,
        game: Optional[str] = None,
        include_writes: bool = True,
        include_rso: bool = True,
        limit: Optional[int] = None,
    ) -> tuple[OperationSpec, ...]:
        needle = query.casefold().strip()
        matches: list[OperationSpec] = []
        for operation in self._operations:
            if game and operation.game != game:
                continue
            if not include_writes and operation.is_write:
                continue
            if not include_rso and operation.auth_mode == "rso":
                continue
            haystack = " ".join(
                (
                    operation.operation_id,
                    operation.accessor_path,
                    operation.summary or "",
                )
            ).casefold()
            if needle and needle not in haystack:
                continue
            matches.append(operation)
            if limit is not None and len(matches) >= limit:
                break
        return tuple(matches)


